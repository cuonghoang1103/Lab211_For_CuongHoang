/**
 * The six concrete shapes of the brief, in the order the report lists them.
 *
 * @author HE176322
 */
public enum ShapeType {

    // A circle (two-dimensional).
    CIRCLE,

    // A square (two-dimensional).
    SQUARE,

    // A triangle given by base and height (two-dimensional).
    TRIANGLE,

    // A sphere (three-dimensional).
    SPHERE,

    // A cube (three-dimensional).
    CUBE,

    // A regular tetrahedron (three-dimensional).
    TETRAHEDRON
}
